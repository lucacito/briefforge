export function applyTemplate(template: Template): ProjectState {
  return {
    ...DEFAULT_PROJECT_STATE,
    ...template.state,
    id: crypto.randomUUID(),
    name: template.label,
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
    currentStep: 0,
  };
}
